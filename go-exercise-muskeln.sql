-- block_types  Kategorien der Übung (Mehrfachauswahl, Werte wie block_type: mobility, skill, grund, hybrid, hypertrophie, finisher, ausdauer)
-- muscles      Muskelgruppen (Mehrfachauswahl, Liste im Editor: Beine, Glutes, Waden, Brust, Schultern, Oberer Rücken, Latissimus …)
-- Erstbefüllung: block_types aus block_type; Muskelgruppen der vorhandenen Übungen nur dort, wo noch keine gesetzt sind.

alter table go_exercise_catalog add column if not exists block_types text[] not null default '{}';
alter table go_exercise_catalog add column if not exists muscles text[] not null default '{}';

update go_exercise_catalog
   set block_types = array[block_type]
 where block_type is not null and coalesce(array_length(block_types, 1), 0) = 0;

