-- go-admin-tickets.sql — Admin: Rolle Admin vergeben (z. B. GbR-Mitglieder) und Tickets (Änderungswünsche)
-- Idempotent. Im Supabase SQL-Editor (gogogo, agpyse…) ausführen. Voraussetzung: go-admin.sql.
--
-- go_admin_set_admin(account, on)  Admin-Rechte geben oder entziehen; nicht sich selbst, mindestens ein Admin bleibt
-- go_tickets                       Wünsche aus Admin → Tickets: Bereich (Frontend/Backend), Abschnitt, Unterkategorie,
--                                  Freitext, Status; Nummer (#) fortlaufend. Nur Admins lesen und schreiben.

create or replace function go_admin_set_admin(p_account uuid, p_on boolean)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not go_is_admin() then raise exception 'not_allowed'; end if;
  if not p_on and p_account = go_current_account_id() then raise exception 'self'; end if;
  if not p_on and (select count(*) from go_accounts where is_admin and deleted_at is null and id <> p_account) = 0 then
    raise exception 'last_admin';
  end if;
  update go_accounts set is_admin = coalesce(p_on, false) where id = p_account;
end $$;
grant execute on function go_admin_set_admin(uuid, boolean) to anon, authenticated;

create table if not exists go_tickets (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  created_by uuid references go_accounts(id) on delete set null,
  created_name text,
  area text not null check (area in ('frontend', 'backend')),
  section text not null,
  sub text,
  body text not null,
  status text not null default 'offen' check (status in ('offen', 'in Arbeit', 'erledigt')),
  updated_at timestamptz not null default now()
);
alter table go_tickets enable row level security;
drop policy if exists "go_tickets_admin" on go_tickets;
create policy "go_tickets_admin" on go_tickets for all to anon, authenticated
  using (go_is_admin()) with check (go_is_admin());
