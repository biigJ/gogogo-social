-- go-pt-blocks.sql — PT-Kalender: Blöcke aus importiertem Kalender (.ics), ohne Titel (pt-calendar.js, Zahnrad)
-- Idempotent. Voraussetzung: go-pt-kalender.sql. Coachees sehen die Blöcke nur als belegte Stunden über go_coach_busy.

create table if not exists go_coach_blocks (
  id bigint generated by default as identity primary key,
  coach_id uuid not null references go_accounts(id) on delete cascade,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  source text not null default 'ics',
  created_at timestamptz not null default now(),
  constraint go_coach_blocks_range_check check (ends_at > starts_at)
);
create index if not exists go_coach_blocks_coach_idx on go_coach_blocks (coach_id, starts_at);
alter table go_coach_blocks enable row level security;
drop policy if exists "coach_blocks_own" on go_coach_blocks;
create policy "coach_blocks_own" on go_coach_blocks for all to anon, authenticated
  using (coach_id = go_current_account_id()) with check (coach_id = go_current_account_id());

/* belegte Stunden: Events, PT-Termine und importierte Blöcke (je angebrochene Stunde eine Zeile) */
create or replace function go_coach_busy(p_coach uuid, p_from timestamptz, p_to timestamptz)
returns table (starts_at timestamptz, kind text)
language sql
stable
security definer
set search_path = public
as $$
  select e.starts_at, 'event'::text
    from events e
   where e.user_id = p_coach
     and e.starts_at >= p_from and e.starts_at < p_to
     and coalesce(e.status, 'geplant') <> 'ausgefallen'
     and coalesce(e.item_type, '') not in ('nutrition_log')
     /* 12:00:00 UTC = Event ohne Uhrzeit, blockiert keine Stunde */
     and not (extract(hour from e.starts_at at time zone 'UTC') = 12 and extract(minute from e.starts_at at time zone 'UTC') = 0 and extract(second from e.starts_at at time zone 'UTC') = 0)
  union all
  select s.session_at, 'pt'::text
    from go_pt_sessions s
    join go_pt_bookings b on b.id = s.booking_id
   where b.coach_id = p_coach
     and s.session_at >= p_from and s.session_at < p_to
     and s.status in ('proposed', 'confirmed')
  union all
  select h, 'block'::text
    from go_coach_blocks k,
         generate_series(date_trunc('hour', greatest(k.starts_at, p_from)), least(k.ends_at, p_to) - interval '1 second', interval '1 hour') h
   where k.coach_id = p_coach
     and k.ends_at > p_from and k.starts_at < p_to
$$;
grant execute on function go_coach_busy(uuid, timestamptz, timestamptz) to anon, authenticated;
